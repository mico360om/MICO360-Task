export class PdfDocument {
  readonly pageWidth: number; // A4, the paper size used in Oman
  readonly pageHeight: number;
  readonly margin = MARGIN;
  readonly bottomMargin = 62; // leaves room for the footer
  /** Where content starts on pages after the first when a running header is drawn above it. */
  private readonly continuationTop: number;

  private readonly doc: PDFKit.PDFDocument;
  /** Top-down cursor (pdfkit coordinates): where the next block starts. */
  private y: number;
  private built: Buffer | null = null;
  private builtPages = 0;

  /** Resolved brand palette used by headings, rules, labels and the footer. */
  private readonly pal: { ink: RGB; muted: RGB; brand: RGB; line: RGB };

  constructor(private readonly opts: PdfDocumentOptions = {}) {
    const landscape = opts.orientation === 'landscape';
    this.pageWidth = landscape ? 841.89 : 595.28;
    this.pageHeight = landscape ? 595.28 : 841.89;
    this.continuationTop = opts.runningTitle ? this.margin + 14 : this.margin;
    const p = opts.palette ?? {};
    this.pal = {
      ink: p.ink ? hexToRgb(p.ink, INK) : INK,
      muted: p.muted ? hexToRgb(p.muted, MUTED) : MUTED,
      brand: p.brand ? hexToRgb(p.brand, BRAND) : BRAND,
      line: p.line ? hexToRgb(p.line, LINE) : LINE,
    };
    this.doc = new PDFDocument({
      size: 'A4',
      layout: landscape ? 'landscape' : 'portrait',
      margin: 0,
      bufferPages: true, // footers ("Page N of M") are drawn once the page count is known
      displayTitle: Boolean(opts.title),
      info: opts.title ? { Title: opts.title } : {},
    });
    registerPdfFonts(this.doc);
    this.y = this.margin;
  }

  private get contentWidth(): number {
    return this.pageWidth - this.margin * 2;
  }

  private get contentBottom(): number {
    return this.pageHeight - this.bottomMargin;
  }

  /** Number of pages so far (the final count once built). */
  get pageCount(): number {
    return this.built ? this.builtPages : this.doc.bufferedPageRange().count;
  }

  private newPage(): void {
    this.doc.addPage({ size: 'A4', layout: this.opts.orientation === 'landscape' ? 'landscape' : 'portrait', margin: 0 });
    this.y = this.continuationTop;
  }

  /** Room left on the current page, in points. */
  get remaining(): number {
    return this.contentBottom - this.y;
  }

  /** Keep the next `height` points together: start a new page if they don't fit here. */
  keepTogether(height: number): this {
    this.ensure(height);
    return this;
  }

  /** Start a new page unless `height` still fits (never loops on an over-tall block at a page top). */
  private ensure(height: number): void {
    if (this.y + height > this.contentBottom && this.y > this.continuationTop + 0.5) this.newPage();
  }

  /** Width of a string in points at the given size/weight (shaped, so Arabic joins are measured correctly). */
  textWidth(text: string, size: number, bold = false): number {
    return measureText(text, size, bold);
  }

  private fillRect(x: number, top: number, w: number, h: number, color: RGB): void {
    this.doc.rect(x, top, w, h).fill(toHex(color));
  }

  /** Draw a laid-out line on `baseline`, aligned inside [left, left + width]. */
  private placeLine(line: TextLine, left: number, width: number, baseline: number, size: number, color: RGB, align: TextAlign): void {
    const effective = align === 'start' ? (line.rtl ? 'right' : 'left') : align;
    const x = effective === 'right' ? left + width - line.width : effective === 'center' ? left + (width - line.width) / 2 : left;
    drawTextLine(this.doc, line, x, baseline, size, toHex(color));
  }

  /** Draw the brand logo mark: a rounded gradient tile with a white check + progress dot. `y` is the tile's bottom edge in PDF (bottom-up) space. */
  logoMark(x: number, y: number, size: number, from?: RGB, to?: RGB): this {
    const c0 = from ?? this.pal.brand;
    const c1 = to ?? darken(this.pal.brand, 0.4);
    const top = this.pageHeight - y - size;
    const r = size * 0.22;
    const grad = this.doc.linearGradient(x, top, x, top + size);
    grad.stop(0, toHex(c0)).stop(1, toHex(c1));
    this.doc.save();
    this.doc.roundedRect(x, top, size, size, r).clip();
    this.doc.rect(x, top, size, size).fill(grad);
    this.doc.restore();
    // White check mark (stroked, round caps).
    this.doc
      .save()
      .lineWidth(size * 0.1)
      .lineCap('round')
      .lineJoin('round')
      .moveTo(x + size * 0.27, top + size * 0.5)
      .lineTo(x + size * 0.43, top + size * 0.66)
      .lineTo(x + size * 0.72, top + size * 0.36)
      .stroke(toHex(WHITE))
      .restore();
    // Small white progress node at the top-right.
    this.doc.circle(x + size * 0.72, top + size * 0.26, size * 0.07).fill(toHex(WHITE));
    return this;
  }

  /**
   * A branded document header: the logo mark, product name + tagline, an eyebrow label,
   * and a brand rule beneath. Positions itself from the current cursor and advances past it.
   */
  brandHeader(opts: { title: string; subtitle?: string; eyebrow?: string; from?: RGB; to?: RGB; badge?: HeaderBadge }): this {
    const s = 42;
    const top = this.y;
    this.logoMark(this.margin, this.pageHeight - top - s, s, opts.from, opts.to);
    this.y = this.headerText(top, s, opts) + 10;
    this.fillRect(this.margin, this.y, this.contentWidth, 2, this.pal.brand);
    this.y += 2 + 12;
    return this;
  }

  /**
   * A header for a document about one project: its picture when this document can print it (see
   * prepareImage — a see-through one is set on white), else its icon (24×24 outline paths) or its
   * initials on its colour; then the eyebrow, the project name and a detail line, an optional badge
   * on the right, and a brand rule beneath.
   */
  identityHeader(opts: { image?: Buffer | null; icon?: readonly string[] | null; initials: string; color?: RGB; title: string; subtitle?: string; eyebrow?: string; badge?: HeaderBadge }): this {
    const s = 46;
    const top = this.y;
    const x = this.margin;
    const image = opts.image ? this.prepareImage(opts.image) : null;
    this.doc.save();
    this.doc.roundedRect(x, top, s, s, s * 0.22).clip();
    if (image) {
      this.doc.rect(x, top, s, s).fill(toHex(WHITE));
      this.doc.image(image, x, top, { fit: [s, s], align: 'center', valign: 'center' });
    } else {
      this.doc.rect(x, top, s, s).fill(toHex(opts.color ?? this.pal.brand));
    }
    this.doc.restore();
    if (image) {
      this.doc.save().lineWidth(0.6).roundedRect(x, top, s, s, s * 0.22).stroke(toHex(this.pal.line)).restore();
    } else if (opts.icon?.length) {
      // The icon at half the tile, as the app draws it: round-capped outlines in white.
      const k = s / 2 / 24;
      this.doc.save().translate(x + s / 4, top + s / 4).scale(k);
      for (const d of opts.icon) this.doc.path(d).lineWidth(1.9).lineCap('round').lineJoin('round').stroke(toHex(WHITE));
      this.doc.restore();
    } else {
      const initials = layoutText(opts.initials.slice(0, 3).toUpperCase(), { size: 17, bold: true })[0]!;
      drawTextLine(this.doc, initials, x + (s - initials.width) / 2, top + s / 2 + 6, 17, toHex(WHITE));
    }
    this.y = this.headerText(top, s, opts) + 10;
    this.fillRect(this.margin, this.y, this.contentWidth, 2, this.pal.brand);
    this.y += 2 + 12;
    return this;
  }

  /**
   * The eyebrow, title and subtitle beside a header's mark (size `s`), and its badge on the right.
   * A line too long for the space first shrinks a little; if it still doesn't fit it wraps (it is
   * never cut), the lines then run down from the top of the mark and the header grows to hold them.
   * Returns where the header's text ends (at least the bottom of the mark).
   */
  private headerText(top: number, s: number, opts: { title: string; subtitle?: string; eyebrow?: string; badge?: HeaderBadge }): number {
    const badgeSize = 7.5;
    const badgeLine = opts.badge ? layoutText(opts.badge.text.toUpperCase(), { size: badgeSize, bold: true })[0]! : null;
    const badgeW = badgeLine ? badgeLine.width + 16 : 0;
    const tx = this.margin + s + 14;
    const tw = this.contentWidth - s - 14 - (badgeW ? badgeW + 12 : 0);
    const fit = (text: string, size: number, min: number, bold: boolean, color: RGB) => {
      let sz = size;
      while (sz > min && measureText(text, sz, bold) > tw) sz -= 0.5;
      return { size: sz, color, lines: layoutText(text, { size: sz, bold, maxWidth: tw }) };
    };
    const eyebrow = opts.eyebrow ? fit(opts.eyebrow.toUpperCase(), 8, 7, true, this.pal.brand) : null;
    const title = fit(opts.title, 17, 12, true, this.pal.ink);
    const subtitle = opts.subtitle ? fit(opts.subtitle, 9, 7.5, false, this.pal.muted) : null;
    const mid = top + s / 2;
    let bottom = top + s;
    if ([eyebrow, title, subtitle].every((b) => !b || b.lines.length === 1)) {
      if (eyebrow) drawTextLine(this.doc, eyebrow.lines[0]!, tx, mid - 12, eyebrow.size, toHex(eyebrow.color));
      drawTextLine(this.doc, title.lines[0]!, tx, mid + 6, title.size, toHex(title.color));
      if (subtitle) drawTextLine(this.doc, subtitle.lines[0]!, tx, mid + 18, subtitle.size, toHex(subtitle.color));
    } else {
      let y = top;
      for (const block of [eyebrow, title, subtitle]) {
        if (!block) continue;
        for (const ln of block.lines) {
          const box = lineBox(ln, block.size);
          drawTextLine(this.doc, ln, tx, y + box.ascent, block.size, toHex(block.color));
          y += box.height;
        }
      }
      bottom = Math.max(bottom, y);
    }
    if (badgeLine && opts.badge) {
      const tone = opts.badge.tone === 'success' ? SUCCESS : opts.badge.tone === 'warning' ? WARNING : this.pal.muted;
      const bx = this.margin + this.contentWidth - badgeW;
      const bh = 18;
      const by = mid - bh / 2;
      this.doc.save().roundedRect(bx, by, badgeW, bh, bh / 2).fill(toHex(mix(tone, WHITE, 0.86))).restore();
      this.doc.save().lineWidth(0.8).roundedRect(bx, by, badgeW, bh, bh / 2).stroke(toHex(tone)).restore();
      drawTextLine(this.doc, badgeLine, bx + 8, by + bh / 2 + badgeSize * 0.36, badgeSize, toHex(tone));
    }
    return bottom;
  }

  /**
   * A band that opens a part of the document ("Final Minutes of Meeting", "Meeting record"): its
   * title in the heading face on a tinted strip with a brand edge. Kept with what follows it.
   */
  partBand(title: string, options: { topGap?: number; keepWith?: number } = {}): this {
    const size = 13.5;
    const h = 30;
    this.spacer(options.topGap ?? 18);
    this.ensure(h + Math.max(40, options.keepWith ?? 0));
    const top = this.y;
    this.doc.save();
    this.doc.roundedRect(this.margin, top, this.contentWidth, h, 5).clip();
    this.fillRect(this.margin, top, this.contentWidth, h, mix(this.pal.brand, WHITE, 0.92));
    this.fillRect(this.margin, top, 4, h, this.pal.brand);
    this.doc.restore();
    const line = layoutText(title, { size, bold: true, family: 'display', maxWidth: this.contentWidth - 28 })[0]!;
    drawTextLine(this.doc, line, this.margin + 14, top + h / 2 + size * 0.36, size, toHex(this.pal.brand));
    this.y = top + h + 8;
    return this;
  }

  /**
   * One line of status on a tinted strip — e.g. "FINAL · Approved by … on …" in green, or
   * "DRAFT · Not yet approved" in amber. Wraps when long.
   */
  statusStrip(text: string, tone: 'success' | 'warning' | 'muted' = 'muted'): this {
    const size = 9.5;
    const color = tone === 'success' ? SUCCESS : tone === 'warning' ? WARNING : this.pal.muted;
    const lines = layoutText(text, { size, bold: true, maxWidth: this.contentWidth - 24 });
    const box = lineBox(null, size, true);
    const h = lines.length * box.height + 12;
    this.ensure(h + 6);
    const top = this.y;
    this.doc.save().roundedRect(this.margin, top, this.contentWidth, h, 5).fill(toHex(mix(color, WHITE, 0.88))).restore();
    this.doc.save().lineWidth(0.7).roundedRect(this.margin, top, this.contentWidth, h, 5).stroke(toHex(mix(color, WHITE, 0.45))).restore();
    lines.forEach((ln, i) => this.placeLine(ln, this.margin + 12, this.contentWidth - 24, top + 6 + i * box.height + box.ascent, size, color, 'start'));
    this.y = top + h + 6;
    return this;
  }

  /** A heading inside a part: bold ink, no rule, kept with the start of what follows. */
  subheading(text: string, options: { topGap?: number; keepWith?: number } = {}): this {
    const size = 11;
    this.spacer(options.topGap ?? 10);
    this.ensure(size * 1.6 + Math.max(28, options.keepWith ?? 0));
    this.text(text, { bold: true, size, color: this.pal.ink, family: 'display', gap: 3 });
    return this;
  }

  /** The room subheading() with these options keeps together (its gap, its line and what it keeps with it): a heading above it keeps this much. */
  subheadingRoom(options: { topGap?: number; keepWith?: number } = {}): number {
    return (options.topGap ?? 10) + 11 * 1.6 + Math.max(28, options.keepWith ?? 0);
  }

  /** The height text() would take for this paragraph (its gap included), in points. */
  textHeight(content: string, options: TextOptions = {}): number {
    const size = options.size ?? 10.5;
    const width = this.contentWidth - (options.inset ?? 0) - (options.indent ?? 0);
    const lines = layoutText(content, { size, bold: options.bold ?? false, maxWidth: width, direction: options.direction, family: options.family });
    return lines.reduce((h, ln) => h + lineBox(ln, size).height, 0) + (options.gap ?? 0);
  }

  /**
   * "Label: value" pairs in two columns, each with its own label width; values wrap within their
   * column. Kept together on one page.
   */
  keyValueColumns(left: ReadonlyArray<readonly [string, string]>, right: ReadonlyArray<readonly [string, string]>, options: { size?: number } = {}): this {
    const size = options.size ?? 10.5;
    const gutter = 24;
    const colW = (this.contentWidth - gutter) / 2;
    const columns = [left, right];
    const laid = columns.map((col) => {
      const labels = col.map(([label]) => layoutText(label, { size, bold: true })[0]!);
      const labelW = Math.max(0, ...labels.map((l) => l.width)) + size * 0.9;
      const rows = col.map(([, value], i) => {
        const values = layoutText(value || '—', { size, maxWidth: colW - labelW });
        const boxes = values.map((ln, j) => lineBox(ln, size, ln.arabic || (j === 0 && labels[i]!.arabic)));
        return { label: labels[i]!, values, boxes, height: boxes.reduce((h, b) => h + b.height, 0) };
      });
      return { labelW, rows, height: rows.reduce((h, r) => h + r.height, 0) };
    });
    this.ensure(Math.max(...laid.map((c) => c.height)));
    const top = this.y;
    laid.forEach((col, c) => {
      const left = this.margin + c * (colW + gutter);
      let y = top;
      for (const row of col.rows) {
        row.values.forEach((ln, j) => {
          const box = row.boxes[j]!;
          const baseline = y + box.ascent;
          if (j === 0) this.placeLine(row.label, left, col.labelW, baseline, size, this.pal.muted, 'left');
          this.placeLine(ln, left + col.labelW, colW - col.labelW, baseline, size, this.pal.ink, row.values.length === 1 ? 'left' : 'start');
          y += box.height;
        });
      }
    });
    this.y = top + Math.max(...laid.map((c) => c.height));
    return this;
  }

  /** Add empty vertical space (points). At a page break the space is dropped rather than carried over. */
  spacer(height: number): this {
    if (this.y + height > this.contentBottom) this.newPage();
    else this.y += height;
    return this;
  }

  /** A flowing paragraph; honors embedded "\n", wraps to the content width, aligns RTL paragraphs right. */
  text(content: string, options: TextOptions = {}): this {
    const size = options.size ?? 10.5;
    const width = this.contentWidth - (options.inset ?? 0) - (options.indent ?? 0);
    return this.flowLines(layoutText(content, { size, bold: options.bold ?? false, maxWidth: width, direction: options.direction, family: options.family }), size, options);
  }

  /** A flowing paragraph of formatted runs (bold, italic, underlined, highlighted, links), laid out as text() lays out plain text. */
  styledText(runs: StyledRun[], options: TextOptions = {}): this {
    const size = options.size ?? 10.5;
    const width = this.contentWidth - (options.inset ?? 0) - (options.indent ?? 0);
    return this.flowLines(layoutStyledText(runs, { size, bold: options.bold ?? false, maxWidth: width, direction: options.direction, family: options.family }), size, options);
  }

  /** Draw laid-out lines down the page (see TextOptions for indent, inset and bar). */
  private flowLines(lines: TextLine[], size: number, options: TextOptions): this {
    const color = options.color ?? this.pal.ink;
    const indent = options.indent ?? 0;
    const left = this.margin + (options.inset ?? 0);
    const width = this.contentWidth - (options.inset ?? 0) - indent;
    for (const line of lines) {
      const box = lineBox(line, size);
      this.ensure(box.height);
      if (options.bar) this.fillRect(Math.max(this.margin, left - 10), this.y, 1.5, box.height, options.bar);
      this.placeLine(line, line.rtl ? left : left + indent, width, this.y + box.ascent, size, color, options.align ?? 'start');
      this.y += box.height;
    }
    if (options.gap) this.y += options.gap;
    return this;
  }

  /**
   * A checklist item: a drawn box (filled with a white tick when done) and the item's words with a
   * hanging indent, wrapped in full. A right-to-left item has its box on the right. Done items are muted.
   */
  checkItem(content: string, done: boolean, options: { size?: number; direction?: TextDirection } = {}): this {
    const size = options.size ?? 10;
    const box = Math.round(size * 0.95 * 10) / 10;
    const gutter = box + 7;
    const width = this.contentWidth - gutter;
    const lines = layoutText(content, { size, maxWidth: width, direction: options.direction });
    const rtl = lines[0]?.rtl ?? false;
    lines.forEach((ln, i) => {
      const lb = lineBox(ln, size);
      this.ensure(lb.height);
      const baseline = this.y + lb.ascent;
      if (i === 0) {
        const bx = rtl ? this.pageWidth - this.margin - box : this.margin;
        const by = baseline - size * 0.78;
        if (done) {
          this.doc.save().roundedRect(bx, by, box, box, 2).fill(toHex(SUCCESS)).restore();
          this.doc
            .save()
            .lineWidth(box * 0.14)
            .lineCap('round')
            .lineJoin('round')
            .moveTo(bx + box * 0.24, by + box * 0.52)
            .lineTo(bx + box * 0.43, by + box * 0.7)
            .lineTo(bx + box * 0.77, by + box * 0.3)
            .stroke(toHex(WHITE))
            .restore();
        } else {
          this.doc.save().lineWidth(0.9).roundedRect(bx + 0.45, by + 0.45, box - 0.9, box - 0.9, 2).stroke(toHex(this.pal.muted)).restore();
        }
      }
      this.placeLine(ln, rtl ? this.margin : this.margin + gutter, width, baseline, size, done ? this.pal.muted : this.pal.ink, 'start');
      this.y += lb.height;
    });
    this.y += 2;
    return this;
  }

  /**
   * A picture as this document can print it: a JPEG or PNG (a see-through PNG flattened onto white,
   * see printableImage) that pdfkit can read; null for anything else (WebP, GIF, a damaged file).
   */
  prepareImage(image: Buffer): Buffer | null {
    const printable = printableImage(image);
    if (!printable) return null;
    try {
      // pdfkit reads the picture's header here (its typings leave openImage out).
      (this.doc as unknown as { openImage(src: Buffer): unknown }).openImage(printable);
      return printable;
    } catch {
      return null;
    }
  }

  /**
   * Pictures in a grid (three to a row by default), each fitted into a framed box with its caption
   * under it, wrapped in full. A row is kept whole on one page. Pictures must come from prepareImage.
   */
  imageGrid(items: GridPicture[], options: { columns?: number; height?: number } = {}): this {
    const { cols, gap, w, h, size, capBox } = this.gridLayout(options);
    for (let r = 0; r < items.length; r += cols) {
      const row = items.slice(r, r + cols);
      const captions = row.map((it) => layoutText(it.caption, { size, maxWidth: w }));
      const rowH = h + 4 + Math.max(...captions.map((c) => c.length)) * capBox.height;
      this.ensure(rowH);
      const top = this.y;
      row.forEach((it, i) => {
        const x = this.margin + i * (w + gap);
        this.doc.save().roundedRect(x, top, w, h, 4).fill(toHex(mix(this.pal.line, WHITE, 0.7))).restore();
        this.doc.image(it.image, x + 3, top + 3, { fit: [w - 6, h - 6], align: 'center', valign: 'center' });
        this.doc.save().lineWidth(0.6).roundedRect(x, top, w, h, 4).stroke(toHex(this.pal.line)).restore();
        captions[i]!.forEach((ln, li) => this.placeLine(ln, x, w, top + h + 4 + li * capBox.height + capBox.ascent, size, this.pal.muted, 'start'));
      });
      this.y = top + rowH + gap;
    }
    return this;
  }

  /** The height of imageGrid()'s first row of these pictures (0 for none): a heading above the grid keeps this much. */
  imageGridFirstRowHeight(items: Pick<GridPicture, 'caption'>[], options: { columns?: number; height?: number } = {}): number {
    if (items.length === 0) return 0;
    const { cols, w, h, size, capBox } = this.gridLayout(options);
    const lines = items.slice(0, cols).map((it) => layoutText(it.caption, { size, maxWidth: w }).length);
    return h + 4 + Math.max(...lines) * capBox.height;
  }

  private gridLayout(options: { columns?: number; height?: number }) {
    const cols = options.columns ?? 3;
    const gap = 12;
    const w = (this.contentWidth - gap * (cols - 1)) / cols;
    const h = options.height ?? Math.round(w * 0.72);
    const size = 8;
    return { cols, gap, w, h, size, capBox: lineBox(null, size, true) };
  }

  /** A section heading: bold, slightly larger, with a hairline rule beneath. Kept with what follows it. */
  heading(text: string, options: { size?: number; color?: RGB; topGap?: number; keepWith?: number } = {}): this {
    const size = options.size ?? 12.5;
    this.spacer(options.topGap ?? 14);
    // Heading + rule + the start of what follows (at least two lines, or `keepWith` points). A long
    // heading counts all its lines (one line keeps the room it always kept).
    const own = Math.max(size * 1.8, this.textHeight(text, { bold: true, size, family: 'display' }));
    this.ensure(own + 9 + Math.max(32, Math.min(options.keepWith ?? 0, this.contentBottom - this.continuationTop - own - 9)));
    this.text(text, { bold: true, size, color: options.color ?? this.pal.brand, family: 'display' });
    this.y += 3;
    this.fillRect(this.margin, this.y, this.contentWidth, 0.7, this.pal.line);
    this.y += 6;
    return this;
  }

  /**
   * A "Label: value" row; the value wraps under a hanging indent aligned past the label.
   * A one-line value sits right after its label; a wrapped right-to-left value is set
   * flush right like any Arabic paragraph.
   */
  keyValue(label: string, value: string, options: { size?: number } = {}): this {
    const size = options.size ?? 10.5;
    const labelLine = layoutText(label, { size, bold: true })[0]!;
    const labelWidth = labelLine.width + size * 0.9;
    const valueWidth = this.contentWidth - labelWidth;
    const valueLines = layoutText(value || '—', { size, maxWidth: valueWidth });
    valueLines.forEach((ln, i) => {
      // Label and first value line share one baseline, even when only one of them is Arabic.
      const box = lineBox(ln, size, ln.arabic || (i === 0 && labelLine.arabic));
      this.ensure(box.height);
      const baseline = this.y + box.ascent;
      if (i === 0) this.placeLine(labelLine, this.margin, labelWidth, baseline, size, this.pal.muted, 'left');
      this.placeLine(ln, this.margin + labelWidth, valueWidth, baseline, size, this.pal.ink, valueLines.length === 1 ? 'left' : 'start');
      this.y += box.height;
    });
    return this;
  }

  /** A bullet list item with a hanging indent; a small square marks it (on the right for RTL items). */
  bullet(content: string, options: { indent?: number; color?: RGB; size?: number; direction?: TextDirection } = {}): this {
    const size = options.size ?? 10.5;
    const indent = options.indent ?? 0;
    const marker = 12;
    const width = this.contentWidth - indent - marker;
    const lines = layoutText(content, { size, maxWidth: width, direction: options.direction });
    const rtl = lines[0]?.rtl ?? false;
    lines.forEach((ln, i) => {
      const box = lineBox(ln, size);
      this.ensure(box.height);
      const baseline = this.y + box.ascent;
      if (i === 0) {
        const sq = 2.6;
        const sx = rtl ? this.pageWidth - this.margin - indent - 1 - sq : this.margin + indent + 1;
        this.fillRect(sx, baseline - size * 0.28 - sq, sq, sq, options.color ?? this.pal.brand);
      }
      this.placeLine(ln, rtl ? this.margin : this.margin + indent + marker, width, baseline, size, this.pal.ink, 'start');
      this.y += box.height;
    });
    return this;
  }

  /** A numbered list item with a hanging indent aligned past the number (mirrored for RTL items). */
  numbered(marker: string, content: string, options: { indent?: number; size?: number; direction?: TextDirection } = {}): this {
    const size = options.size ?? 10.5;
    const indent = options.indent ?? 0;
    const gutter = Math.max(16, measureText(marker, size, true) + size * 0.3 + 4);
    const width = this.contentWidth - indent - gutter;
    const lines = layoutText(content, { size, maxWidth: width, direction: options.direction });
    const rtl = lines[0]?.rtl ?? false;
    const markerLine = layoutText(marker, { size, bold: true, direction: rtl ? 'rtl' : 'ltr' })[0]!;
    lines.forEach((ln, i) => {
      const box = lineBox(ln, size);
      this.ensure(box.height);
      const baseline = this.y + box.ascent;
      if (i === 0) {
        const mx = rtl ? this.pageWidth - this.margin - indent - markerLine.width : this.margin + indent;
        drawTextLine(this.doc, markerLine, mx, baseline, size, toHex(this.pal.brand));
      }
      this.placeLine(ln, rtl ? this.margin : this.margin + indent + gutter, width, baseline, size, this.pal.ink, 'start');
      this.y += box.height;
    });
    return this;
  }

  /**
   * Formatted text, block by block: paragraphs, a heading and (nested) bulleted or numbered lists,
   * in bold / italic faces, with underline, highlight and clickable links. `lead` puts a bullet or a
   * number before the first line and hangs everything after it (a note in a list of notes). Right-
   * to-left blocks are set from the right edge, their markers too.
   */
  richBlocks(blocks: PdfRichBlock[], options: { lead?: string; size?: number } = {}): this {
    const size = options.size ?? 10.5;
    const leadW = options.lead ? this.markerWidth(options.lead, size) : 0;
    blocks.forEach((b, bi) => {
      const heading = b.kind === 'heading';
      const s = heading ? size + 0.5 : size;
      const runs = heading ? b.runs.map((r) => ({ ...r, bold: true })) : b.runs;
      const itemIndent = b.kind === 'item' ? (b.level ?? 0) * 14 : 0;
      const markerW = b.kind === 'item' ? this.markerWidth(b.marker ?? BULLET, s) : 0;
      const textIndent = leadW + itemIndent + markerW;
      const width = this.contentWidth - textIndent;
      const lines = layoutStyledText(runs, { size: s, maxWidth: width });
      const rtl = lines[0]?.rtl ?? false;
      if (bi > 0) this.y += heading ? 4 : 2;
      lines.forEach((ln, i) => {
        const box = lineBox(ln, s);
        this.ensure(box.height);
        const baseline = this.y + box.ascent;
        if (i === 0 && bi === 0 && options.lead) this.drawMarker(options.lead, 0, baseline, s, rtl);
        if (i === 0 && b.kind === 'item') this.drawMarker(b.marker ?? BULLET, leadW + itemIndent, baseline, s, rtl);
        this.placeLine(ln, rtl ? this.margin : this.margin + textIndent, width, baseline, s, this.pal.ink, 'start');
        this.y += box.height;
      });
    });
    return this;
  }

  /** Room a list marker takes before its text. */
  private markerWidth(marker: string, size: number): number {
    return marker === BULLET ? 12 : Math.max(16, measureText(marker, size, true) + size * 0.3 + 4);
  }

  /** A bullet (a small square) or a number, `offset` points in from the starting edge (the right one when right-to-left). */
  private drawMarker(marker: string, offset: number, baseline: number, size: number, rtl: boolean): void {
    if (marker === BULLET) {
      const sq = 2.6;
      const sx = rtl ? this.pageWidth - this.margin - offset - 1 - sq : this.margin + offset + 1;
      this.fillRect(sx, baseline - size * 0.28 - sq, sq, sq, this.pal.brand);
      return;
    }
    const line = layoutText(marker, { size, bold: true, direction: rtl ? 'rtl' : 'ltr' })[0]!;
    const mx = rtl ? this.pageWidth - this.margin - offset - line.width : this.margin + offset;
    drawTextLine(this.doc, line, mx, baseline, size, toHex(this.pal.brand));
  }

  /**
   * The report header: the company logo on the left; the title (Archivo), a subtitle and detail
   * lines (generated, filters) on the right; a brand gradient rule beneath.
   */
  reportHeader(opts: { title: string; subtitle?: string; details?: string[] }): this {
    const top = this.y;
    const logo = companyLogo();
    const logoH = 40;
    const logoW = logo ? logoH * LOGO_ASPECT : logoH;
    if (logo) this.doc.image(logo, this.margin, top, { height: logoH });
    else this.logoMark(this.margin, this.pageHeight - top - logoH, logoH);
    const blockLeft = this.margin + logoW + 24;
    const blockWidth = this.pageWidth - this.margin - blockLeft;
    let by = top;
    const right = (text: string, size: number, color: RGB, opts2: { bold?: boolean; family?: 'text' | 'display' } = {}) => {
      for (const ln of layoutText(text, { size, bold: opts2.bold, family: opts2.family, maxWidth: blockWidth })) {
        const box = lineBox(ln, size);
        this.placeLine(ln, blockLeft, blockWidth, by + box.ascent, size, color, 'right');
        by += box.height;
      }
    };
    right(opts.title, 19, this.pal.ink, { bold: true, family: 'display' });
    if (opts.subtitle) right(opts.subtitle, 10.5, this.pal.brand, { bold: true });
    for (const d of opts.details ?? []) right(d, 8.5, this.pal.muted);
    this.y = Math.max(top + logoH, by) + 10;
    // Brand gradient rule (the web app's #A83326 → #8B1E1E → #5E1414 sheen).
    const grad = this.doc.linearGradient(this.margin, 0, this.pageWidth - this.margin, 0);
    grad.stop(0, toHex(mix(this.pal.brand, WHITE, 0.12))).stop(0.55, toHex(this.pal.brand)).stop(1, toHex(darken(this.pal.brand, 0.33)));
    this.doc.rect(this.margin, this.y, this.contentWidth, 2.5).fill(grad);
    this.y += 2.5 + 14;
    return this;
  }

  private tone(t: StatTile['tone']): RGB {
    return t === 'danger' ? DANGER : t === 'success' ? SUCCESS : t === 'warning' ? WARNING : t === 'muted' ? this.pal.muted : this.pal.brand;
  }

  /**
   * A row of summary tiles: a big value (Archivo) over its label, with a coloured accent. A note
   * sits beside the value when it fits there, otherwise on its own line(s) under the label — it is
   * never cut short. All tiles in the row share the tallest tile's height.
   */
  statTiles(items: StatTile[]): this {
    if (items.length === 0) return this;
    const gap = 10;
    const w = (this.contentWidth - gap * (items.length - 1)) / items.length;
    const inner = w - 20;
    const laid = items.map((it) => {
      // The value shrinks (19 → 11 pt) until it fits on one line, and wraps only if it still doesn't.
      let size = 19;
      while (size > 11 && measureText(it.value, size, true, 'display') > inner) size -= 1;
      const values = layoutText(it.value, { size, bold: true, family: 'display', maxWidth: inner });
      const value = values[0]!;
      const noteWidth = it.note ? measureText(it.note, 9, true) : 0;
      const beside = !it.note || (values.length === 1 && value.width + 6 + noteWidth <= inner);
      const label = layoutText(it.label, { size: 8.5, maxWidth: inner });
      const note = it.note && !beside ? layoutText(it.note, { size: 8.5, bold: true, maxWidth: inner }) : [];
      const extra = (values.length - 1) * size * 1.15;
      return { it, size, values, value, beside, label, note, extra };
    });
    const h = Math.max(56, ...laid.map((l) => 36 + l.extra + 11 * l.label.length + 11 * l.note.length + 6));
    this.ensure(h + 8);
    const top = this.y;
    laid.forEach(({ it, size, values, value, beside, label, note, extra }, i) => {
      const x = this.margin + i * (w + gap);
      const accent = this.tone(it.tone);
      this.doc.roundedRect(x, top, w, h, 6).fill(toHex(mix(accent, WHITE, 0.93)));
      this.doc.save();
      this.doc.roundedRect(x, top, w, h, 6).clip();
      this.fillRect(x, top, 3, h, accent);
      this.doc.restore();
      values.forEach((ln, li) => drawTextLine(this.doc, ln, x + 12, top + 26 + li * size * 1.15, size, toHex(it.tone === 'danger' ? DANGER : this.pal.ink)));
      if (it.note && beside) {
        const n = layoutText(it.note, { size: 9, bold: true })[0]!;
        drawTextLine(this.doc, n, x + 12 + value.width + 6, top + 26, 9, toHex(accent));
      }
      let ly = top + 44 + extra;
      for (const ln of label) {
        drawTextLine(this.doc, ln, x + 12, ly, 8.5, toHex(this.pal.muted));
        ly += 11;
      }
      for (const ln of note) {
        drawTextLine(this.doc, ln, x + 12, ly, 8.5, toHex(accent));
        ly += 11;
      }
    });
    this.y = top + h + 8;
    return this;
  }

  /** Horizontal bars, one per item, scaled to the largest value; each row is kept whole. */
  barList(items: BarItem[], options: { size?: number } = {}): this {
    const size = options.size ?? 9;
    const rowH = 17;
    const labelW = Math.min(170, Math.max(...items.map((it) => measureText(it.label, size)), 40) + 10);
    const valueW = Math.max(...items.map((it) => measureText(String(it.value), size, true)), 14) + 8;
    const barMax = this.contentWidth - labelW - valueW - 6;
    const max = Math.max(...items.map((it) => it.value), 1);
    for (const it of items) {
      this.ensure(rowH);
      const box = lineBox(null, size, true);
      const baseline = this.y + (rowH - box.height) / 2 + box.ascent;
      const label = layoutText(it.label, { size, maxWidth: labelW - 10 })[0];
      if (label) this.placeLine(label, this.margin, labelW - 10, baseline, size, this.pal.ink, 'left');
      const bx = this.margin + labelW;
      this.fillRect(bx, this.y + 5, barMax, rowH - 10, mix(this.pal.line, WHITE, 0.6));
      const bw = (barMax * Math.max(0, it.value)) / max;
      if (bw > 0) this.fillRect(bx, this.y + 5, Math.max(bw, 1.5), rowH - 10, it.color ? hexToRgb(it.color, this.pal.brand) : this.pal.brand);
      const v = layoutText(String(it.value), { size, bold: true })[0]!;
      drawTextLine(this.doc, v, this.pageWidth - this.margin - v.width, baseline, size, toHex(this.pal.ink));
      this.y += rowH;
    }
    this.y += 4;
    return this;
  }

  /** A line chart with a legend, a value axis with gridlines and first/middle/last day labels. Kept whole on one page. */
  lineChart(opts: { labels: string[]; series: ChartSeries[]; height?: number }): this {
    const height = opts.height ?? 170;
    const legendH = 24;
    this.ensure(height + legendH + 6);
    const defaults: RGB[] = [this.pal.ink, this.pal.brand, WARNING, SUCCESS];
    const colors = opts.series.map((s, i) => (s.color ? hexToRgb(s.color, defaults[i % defaults.length]!) : defaults[i % defaults.length]!));
    // Legend.
    let lx = this.margin;
    opts.series.forEach((s, i) => {
      this.fillRect(lx, this.y + 4, 9, 9, colors[i]!);
      const name = layoutText(s.name, { size: 8.5 })[0]!;
      drawTextLine(this.doc, name, lx + 13, this.y + 12, 8.5, toHex(this.pal.ink));
      lx += 13 + name.width + 16;
    });
    this.y += legendH;
    const top = this.y;
    const max = Math.max(1, ...opts.series.flatMap((s) => s.values));
    const step = [1, 2, 5, 10, 20, 25, 50, 100, 200, 250, 500, 1000, 2000, 5000].find((st) => st * 4 >= max) ?? Math.ceil(max / 4);
    const yMax = step * 4;
    const axisW = Math.max(measureText(String(yMax), 8), 10) + 8;
    const left = this.margin + axisW;
    const plotW = this.contentWidth - axisW;
    const plotH = height - 16;
    const yOf = (v: number) => top + plotH - (plotH * v) / yMax;
    for (let g = 0; g <= 4; g++) {
      const gy = yOf(g * step);
      this.fillRect(left, gy, plotW, 0.5, g === 0 ? this.pal.muted : mix(this.pal.line, WHITE, 0.3));
      const t = layoutText(String(g * step), { size: 8 })[0]!;
      drawTextLine(this.doc, t, left - 6 - t.width, gy + 3, 8, toHex(this.pal.muted));
    }
    const n = opts.labels.length;
    const xOf = (i: number) => (n <= 1 ? left + plotW / 2 : left + (plotW * i) / (n - 1));
    opts.series.forEach((s, si) => {
      const pts = s.values.map((v, i) => [xOf(i), yOf(Math.max(0, v))] as const);
      if (pts.length === 0) return;
      this.doc.save().lineWidth(1.6).lineJoin('round').lineCap('round');
      this.doc.moveTo(pts[0]![0], pts[0]![1]);
      for (const [x, y] of pts.slice(1)) this.doc.lineTo(x, y);
      if (pts.length === 1) this.doc.lineTo(pts[0]![0] + 0.1, pts[0]![1]);
      this.doc.stroke(toHex(colors[si]!)).restore();
      if (pts.length <= 31) for (const [x, y] of pts) this.doc.circle(x, y, 1.6).fill(toHex(colors[si]!));
    });
    const marks = n <= 1 ? [0] : [...new Set([0, Math.floor((n - 1) / 2), n - 1])];
    for (const i of marks) {
      const t = layoutText(opts.labels[i] ?? '', { size: 8 })[0];
      if (!t) continue;
      const x = Math.min(Math.max(xOf(i) - t.width / 2, left), this.pageWidth - this.margin - t.width);
      drawTextLine(this.doc, t, x, top + plotH + 12, 8, toHex(this.pal.muted));
    }
    this.y = top + height + 6;
    return this;
  }

  /** A full-width hairline rule. */
  rule(color?: RGB): this {
    this.spacer(4);
    this.ensure(4);
    this.fillRect(this.margin, this.y, this.contentWidth, 0.6, color ?? this.pal.line);
    this.y += 4;
    return this;
  }

  /**
   * A data table spanning the content width. Columns are sized from their content,
   * cells wrap within their column, rows never split across pages (unless one is taller
   * than a page on its own: then its lines continue on the next page, so nothing is cut),
   * and the header row repeats at the top of every page. Numeric columns align right;
   * text cells align to their own direction (Arabic right, English left).
   */
  table(
    columns: TableColumn[],
    rows: ReadonlyArray<ReadonlyArray<string>>,
    options: {
      size?: number;
      cellColor?: (row: number, col: number) => RGB | null;
      /** The column that takes the width left over (the others keep their natural width); by default every column gets a share. */
      wide?: number;
      /**
       * Balanced columns (see fitColumns): each at least as wide as its longest word, the spare
       * room to the columns with the most to say; a table too wide for that sets its type smaller,
       * down to `minSize`, before any word breaks.
       */
      fit?: { minSize?: number };
    } = {},
  ): this {
    const n = columns.length;
    if (n === 0) return this;
    const layout = this.tableLayout(columns, rows, options.size ?? 8.5, options.wide, options.fit);
    const { size, padX, padY, total, widths, numeric, header, body } = layout;

    // Lines [from, to) of a row: all of it, or the part of a too-tall row that goes on this page.
    const drawRow = (row: TableRowLayout, fill: RGB | null, ri: number | null, from = 0, to = row.lines) => {
      const box = row.box;
      const height = (to - from) * box.height + padY * 2;
      if (fill) this.fillRect(this.margin, this.y, total, height, fill);
      let x = this.margin;
      row.laid.forEach((lines, ci) => {
        const color = (ri !== null && options.cellColor?.(ri, ci)) || this.pal.ink;
        for (let li = from; li < Math.min(to, lines.length); li++) {
          const baseline = this.y + padY + (li - from) * box.height + box.ascent;
          this.placeLine(lines[li]!, x + padX, widths[ci]! - padX * 2, baseline, size, color, numeric[ci] ? 'right' : 'start');
        }
        x += widths[ci]!;
      });
      this.fillRect(this.margin, this.y + height - 0.5, total, 0.5, this.pal.line);
      this.y += height;
    };

    const headerFill = mix(this.pal.brand, WHITE, 0.9);
    const stripe = mix(this.pal.line, WHITE, 0.72);
    const plan = paginateRows(
      body.map((r) => r.lines),
      {
        lineHeight: header.box.height,
        lineHeights: body.map((r) => r.box.height),
        padY,
        header: header.height,
        room: this.remaining,
        pageRoom: this.contentBottom - this.continuationTop,
        atTop: this.y <= this.continuationTop + 0.5,
      },
    );
    if (plan.newPage) this.newPage();
    plan.pages.forEach((pieces, pi) => {
      if (pi > 0) this.newPage();
      drawRow(header, headerFill, null); // the header on every page the table is on
      for (const p of pieces) drawRow(body[p.row]!, p.row % 2 === 1 ? stripe : null, p.row, p.from, p.to);
    });
    return this;
  }

  /**
   * The height a table would take if drawn now on one page (header + every row, or just its first
   * `firstRows` rows — columns sized from all of them, as table() sizes them), in points.
   */
  tableHeight(columns: TableColumn[], rows: ReadonlyArray<ReadonlyArray<string>>, options: { size?: number; wide?: number; firstRows?: number; fit?: { minSize?: number } } = {}): number {
    if (columns.length === 0) return 0;
    const { header, body } = this.tableLayout(columns, rows, options.size ?? 8.5, options.wide, options.fit);
    return header.height + body.slice(0, options.firstRows ?? body.length).reduce((s, r) => s + r.height, 0);
  }

  private tableLayout(columns: TableColumn[], rows: ReadonlyArray<ReadonlyArray<string>>, baseSize: number, wide?: number, fit?: { minSize?: number }) {
    const padX = TABLE_PAD_X;
    const padY = 3;
    const total = this.contentWidth;
    let size = baseSize;
    let widths: number[];
    if (fit) {
      const plan = fitColumns(measureColumns(columns, rows), total, { size, minSize: fit.minSize, padX, wide });
      size = plan.size;
      widths = plan.widths;
    } else {
      widths = this.naturalColumnWidths(columns, rows, size, wide);
    }
    // One line height for every cell (Arabic-safe), so baselines line up across a row and every row
    // has the same rhythm whether or not it contains Arabic. A balanced (fit) table gives each row
    // its own: the normal one, or the taller Arabic one when the row has Arabic (its cells still
    // share one baseline).
    const box = lineBox(null, size, true);

    const numeric = columns.map((c, ci) => {
      if (c.align === 'right') return true;
      if (c.align === 'left') return false;
      const vals = rows.map((r) => (r[ci] ?? '').trim()).filter((v) => v.length > 0);
      return vals.length > 0 && vals.every((v) => NUMERIC.test(v));
    });

    // Every line of every cell is kept: a row taller than a page continues on the next (see table()).
    const layoutRow = (cells: ReadonlyArray<string>, bold: boolean): TableRowLayout => {
      const laid = columns.map((_, ci) => layoutText(cells[ci] ?? '', { size, bold, maxWidth: widths[ci]! - padX * 2 }));
      const lines = Math.max(1, ...laid.map((l) => l.length));
      const rowBox = fit ? lineBox(null, size, laid.some((cell) => cell.some((ln) => ln.arabic))) : box;
      return { laid, lines, box: rowBox, height: lines * rowBox.height + padY * 2 };
    };

    const header = layoutRow(
      columns.map((c) => c.header),
      true,
    );
    const body = rows.map((r) => layoutRow(r, false));
    return { size, padX, padY, total, widths, numeric, header, body };
  }

  /** The original column sizing: natural single-line widths, stretched to fill or water-filled to fit. */
  private naturalColumnWidths(columns: TableColumn[], rows: ReadonlyArray<ReadonlyArray<string>>, size: number, wide?: number): number[] {
    const n = columns.length;
    const padX = TABLE_PAD_X;
    const total = this.contentWidth;
    const natural = columns.map((c, ci) => {
      let w = measureText(c.header, size, true);
      for (const r of rows) w = Math.max(w, measureText(r[ci] ?? '', size));
      return Math.max(w + padX * 2, 30);
    });
    const naturalSum = natural.reduce((a, b) => a + b, 0);
    const widths = new Array<number>(n).fill(0);
    if (naturalSum <= total && wide !== undefined && wide >= 0 && wide < n) {
      // The other columns get a little air (up to 14 pt each); the wide one takes the rest.
      const air = n > 1 ? Math.min(14, (total - naturalSum) / n) : 0;
      natural.forEach((w, i) => (widths[i] = w + air));
      widths[wide] = natural[wide]! + (total - naturalSum) - air * (n - 1);
    } else if (naturalSum <= total) {
      natural.forEach((w, i) => (widths[i] = w + (total - naturalSum) * (w / naturalSum)));
    } else {
      // Columns narrower than a fair share keep their natural width; the rest split what is left.
      let open = natural.map((_, i) => i);
      let remaining = total;
      while (open.length > 0) {
        const fair = remaining / open.length;
        const small = open.filter((i) => natural[i]! <= fair);
        if (small.length === 0) {
          open.forEach((i) => (widths[i] = fair));
          break;
        }
        for (const i of small) {
          widths[i] = natural[i]!;
          remaining -= natural[i]!;
        }
        open = open.filter((i) => natural[i]! > fair);
      }
    }
    return widths;
  }

  /** Serialize to a PDF byte buffer (idempotent). */
  build(): Buffer {
    if (this.built) return this.built;
    const range = this.doc.bufferedPageRange();
    const total = range.count;
    const footerLines = (this.opts.footerLeft ?? '').split('\n').filter((l) => l.length > 0);
    const { line, muted, brand } = this.pal;

    const logo = this.opts.runningTitle ? companyLogo() : null;
    for (let i = 0; i < total; i++) {
      this.doc.switchToPage(range.start + i);
      if (i > 0 && this.opts.runningTitle) {
        // Slim running header: small logo, the document title on the right, a hairline.
        const h = 16;
        if (logo) this.doc.image(logo, this.margin, 26, { height: h });
        else this.logoMark(this.margin, this.pageHeight - 26 - h, h);
        // A title too long for the header ends with "…" (the first page's own header shows it in full).
        const t = fitLine(this.opts.runningTitle.replace(/\s+/g, ' '), { size: 8, maxWidth: this.contentWidth - h * LOGO_ASPECT - 20 });
        drawTextLine(this.doc, t.line, this.pageWidth - this.margin - t.line.width, 37, t.size, toHex(muted));
        this.fillRect(this.margin, 48, this.contentWidth, 0.6, line);
      }
      // Footer: hairline (with a short brand accent at the left) + credit lines + page number.
      const ruleTop = this.pageHeight - 46;
      this.fillRect(this.margin, ruleTop + 1, this.contentWidth, 0.6, line);
      this.fillRect(this.margin, ruleTop, 40, 1.6, brand);
      const pageLine = layoutText(`Page ${i + 1} of ${total}`, { size: 8 })[0]!;
      const leftWidth = this.contentWidth - pageLine.width - 12;
      footerLines.forEach((text, li) => {
        // The footer is a left-aligned block: lay each line out left-to-right (Arabic runs still read RTL).
        // A line too long for it shrinks a little, then ends with "…": never cut off without a sign.
        const ln = fitLine(text, { size: 8, minSize: 6.5, maxWidth: leftWidth, direction: 'ltr' });
        drawTextLine(this.doc, ln.line, this.margin, this.pageHeight - 34 + li * 10.5, ln.size, toHex(muted));
      });
      drawTextLine(this.doc, pageLine, this.pageWidth - this.margin - pageLine.width, this.pageHeight - 34, 8, toHex(muted));
    }

    this.builtPages = total;
    this.doc.end();
    // pdfkit writes the whole file synchronously during end(); drain the stream buffer.
    const chunks: Buffer[] = [];
    for (let c = this.doc.read() as Buffer | null; c !== null; c = this.doc.read() as Buffer | null) chunks.push(c);
    this.built = Buffer.concat(chunks);
    return this.built;
  }
}

/** A table row laid out: each cell's lines, the most lines any cell has, its line box and its height. */
interface TableRowLayout {
  laid: TextLine[][];
  lines: number;
  box: { height: number; ascent: number };
  height: number;
}

/**
 * One line of text that must fit `maxWidth`: set at `size`, or smaller (in half points, down to
 * `minSize`) when it doesn't fit; if it still doesn't, it is cut at the last character that fits
 * and ends with "…", so a shortened line always says so.
 */
function fitLine(text: string, opts: { size: number; minSize?: number; maxWidth: number; direction?: TextDirection }): { line: TextLine; size: number } {
  const one = (t: string, size: number) => layoutText(t, { size, direction: opts.direction })[0]!;
  let size = opts.size;
  let line = one(text, size);
  while (line.width > opts.maxWidth && size - 0.5 >= (opts.minSize ?? opts.size) - 1e-9) {
    size -= 0.5;
    line = one(text, size);
  }
  if (line.width <= opts.maxWidth) return { line, size };
  let lo = 0;
  let hi = text.length;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (measureText(`${text.slice(0, mid).trimEnd()}…`, size) <= opts.maxWidth) lo = mid;
    else hi = mid - 1;
  }
  return { line: one(`${text.slice(0, lo).trimEnd()}…`, size), size };
}
