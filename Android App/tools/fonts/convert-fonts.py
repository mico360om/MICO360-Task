"""
Make the app's font files from the website's own: Web Portal/frontend/src/assets/fonts/*.woff2
(IBM Plex Sans 400/500/600/700 and Archivo 600/700/800/900, each a latin + latin-ext subset).

For every face the two subsets are unpacked to TrueType and merged into one assets/fonts/<Face>.ttf
(if the merge fails, the latin subset alone is kept and SOURCES.json says "merged": false).
Also writes assets/fonts/SOURCES.json (the sha256 of every woff2 used — font-files.test.ts fails
when the website's files change, then run this again), copies the two licences, and writes
src/lib/font-metrics.ts (IBM Plex Sans SemiBold advance widths, for the tab-label fit test).

Run from anywhere: py -3 tools/fonts/convert-fonts.py   (needs: py -3 -m pip install --user fonttools brotli)
"""
import hashlib
import json
import os
import shutil
import sys
import tempfile

from fontTools.merge import Merger
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.normpath(os.path.join(HERE, '..', '..'))
WEB_FONTS = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'Web Portal', 'frontend', 'src', 'assets', 'fonts'))
OUT = os.path.join(APP, 'assets', 'fonts')
METRICS = os.path.join(APP, 'src', 'lib', 'font-metrics.ts')

FACES = [
    ('IBMPlexSans-Regular', 'ibm-plex-sans', 400),
    ('IBMPlexSans-Medium', 'ibm-plex-sans', 500),
    ('IBMPlexSans-SemiBold', 'ibm-plex-sans', 600),
    ('IBMPlexSans-Bold', 'ibm-plex-sans', 700),
    ('Archivo-SemiBold', 'archivo', 600),
    ('Archivo-Bold', 'archivo', 700),
    ('Archivo-ExtraBold', 'archivo', 800),
    ('Archivo-Black', 'archivo', 900),
]
LICENSES = ['LICENSE-IBM-Plex-Sans.txt', 'LICENSE-Archivo.txt']


def sha256(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def unpack(woff2, ttf):
    font = TTFont(woff2, recalcTimestamp=False)
    font.flavor = None
    font.save(ttf)


def convert(face, prefix, weight, tmp):
    names = [f'{prefix}-latin-{weight}-normal.woff2', f'{prefix}-latin-ext-{weight}-normal.woff2']
    paths = [os.path.join(WEB_FONTS, n) for n in names]
    for p in paths:
        if not os.path.exists(p):
            sys.exit(f'missing website font file: {p}')
    ttfs = []
    for n, p in zip(names, paths):
        t = os.path.join(tmp, n.replace('.woff2', '.ttf'))
        unpack(p, t)
        ttfs.append(t)
    target = os.path.join(OUT, f'{face}.ttf')
    try:
        merged = Merger().merge(ttfs)
        merged.recalcTimestamp = False
        merged.save(target)
        ok = True
    except Exception as e:  # keep the latin subset alone rather than no font
        print(f'  merge failed for {face} ({e}); keeping the latin subset only')
        shutil.copyfile(ttfs[0], target)
        ok = False
    print(f'wrote assets/fonts/{face}.ttf')
    return {'sources': {n: sha256(p) for n, p in zip(names, paths)}, 'merged': ok}


def write_metrics():
    font = TTFont(os.path.join(OUT, 'IBMPlexSans-SemiBold.ttf'))
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    upem = font['head'].unitsPerEm
    entries = []
    for code in range(0x20, 0x7F):
        ch = chr(code)
        width = hmtx[cmap[code]][0] / upem
        entries.append(f'  {json.dumps(ch)}: {round(width, 4)},')
    body = '\n'.join(entries)
    text = (
        '// Generated by tools/fonts/convert-fonts.py — do not edit.\n'
        '\n'
        '/** IBM Plex Sans SemiBold advance widths in em (U+0020–U+007E), from assets/fonts/IBMPlexSans-SemiBold.ttf. */\n'
        'export const PLEX_SEMIBOLD_ADVANCE: Readonly<Record<string, number>> = {\n'
        f'{body}\n'
        '};\n'
        '\n'
        '/** The width of `text` in em; a character without a known width counts as `fallbackEm`. */\n'
        'export function textWidthEm(text: string, advances: Readonly<Record<string, number>> = PLEX_SEMIBOLD_ADVANCE, fallbackEm = 0.6): number {\n'
        '  let width = 0;\n'
        '  for (const ch of text) width += advances[ch] ?? fallbackEm;\n'
        '  return width;\n'
        '}\n'
    )
    with open(METRICS, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote src/lib/font-metrics.ts')


def main():
    os.makedirs(OUT, exist_ok=True)
    sources = {}
    with tempfile.TemporaryDirectory() as tmp:
        for face, prefix, weight in FACES:
            sources[face] = convert(face, prefix, weight, tmp)
    with open(os.path.join(OUT, 'SOURCES.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(sources, f, indent=2, sort_keys=True)
        f.write('\n')
    for name in LICENSES:
        shutil.copyfile(os.path.join(WEB_FONTS, name), os.path.join(OUT, name))
    write_metrics()


if __name__ == '__main__':
    main()
